import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from '@playwright/test'
import { format, resolveConfig } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// Match the shared light palette in src/styles/theme.css and SudokuTheme.kt.
const background = '#f5f4ee'
const board = '#fffef9'
const foreground = '#147d71'
const outline = foreground
const grid = '#81958b'
const boardEdge = '#dbdfd5'
const peerRow = '#f0f3e9'
const highlightedCell = '#e0efea'
const tilt = -6
const androidScale = 0.92

// Share the same geometry across both platforms. The mark stays inside Android's
// central 66 dp safe zone; Web crops the 108 dp canvas to the visible 72 dp tile.
const boardPath =
  'M34.75 30.75H73.25Q77.25 30.75 77.25 34.75V73.25Q77.25 77.25 73.25 77.25H34.75Q30.75 77.25 30.75 73.25V34.75Q30.75 30.75 34.75 30.75Z'
const boardEdgePath =
  'M34.75 31.85H73.25Q77.25 31.85 77.25 35.85V74.35Q77.25 78.35 73.25 78.35H34.75Q30.75 78.35 30.75 74.35V35.85Q30.75 31.85 34.75 31.85Z'
const gridPath = 'M46.25 30.75V77.25 M61.75 30.75V77.25 M30.75 46.25H77.25 M30.75 61.75H77.25'
const peerRowPath = 'M30.75 46.25H77.25V61.75H30.75Z'
const highlightedCellPath = 'M46.25 46.25H61.75V61.75H46.25Z'

// Fixed glyph outlines keep the labels identical across platforms without font dependencies.
const numerals = JSON.parse(
  await readFile(resolve(root, 'resources/branding/icon-numerals.json'), 'utf8'),
)
const numeralPath = numerals.map(({ path }) => path).join(' ')

function svg(size, rounded) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="18 18 72 72">
  <style>@media (max-width: 32px) { .grid { stroke-width: 1.5 } .outline { stroke-width: 1.8 } }</style>
  <rect x="18" y="18" width="72" height="72" rx="${rounded ? 16 : 0}" fill="${background}" />
  <g transform="rotate(${tilt} 54 54)">
    <path d="${boardEdgePath}" fill="${boardEdge}" />
    <path d="${boardPath}" fill="${board}" />
    <path d="${peerRowPath}" fill="${peerRow}" />
    <path d="${highlightedCellPath}" fill="${highlightedCell}" />
    <path class="grid" d="${gridPath}" fill="none" stroke="${grid}" stroke-width="0.9" />
    <path class="outline" d="${boardPath}" fill="none" stroke="${outline}" stroke-width="1.5" />
    <path d="${numeralPath}" fill="${foreground}" />
  </g>
</svg>`
}

function androidForeground(monochrome) {
  const color = monochrome ? '#ffffff' : foreground
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:rotation="${tilt}"
        android:scaleX="${androidScale}"
        android:scaleY="${androidScale}"
        android:pivotX="54"
        android:pivotY="54">
        ${monochrome ? '' : `<path android:pathData="${boardEdgePath}" android:fillColor="${boardEdge}" />`}
        ${monochrome ? '' : `<path android:pathData="${boardPath}" android:fillColor="${board}" />`}
        ${monochrome ? '' : `<path android:pathData="${peerRowPath}" android:fillColor="${peerRow}" />`}
        ${monochrome ? '' : `<path android:pathData="${highlightedCellPath}" android:fillColor="${highlightedCell}" />`}
        <path
            android:pathData="${gridPath}"
            android:fillColor="@android:color/transparent"
            android:strokeColor="${monochrome ? color : grid}"
            android:strokeWidth="${monochrome ? 1.1 : 0.9}" />
        <path
            android:pathData="${boardPath}"
            android:fillColor="@android:color/transparent"
            android:strokeColor="${monochrome ? color : outline}"
            android:strokeWidth="1.5" />
        <path
            android:pathData="${numeralPath}"
            android:fillColor="${color}" />
    </group>
</vector>
`.replaceAll(/^ +$/gm, '')
}

async function writeAsset(path, content) {
  const destination = resolve(root, path)
  await mkdir(dirname(destination), { recursive: true })
  await writeFile(destination, content)
}

const browser = await chromium.launch()

try {
  const page = await browser.newPage({ deviceScaleFactor: 1 })
  const rasterAssets = [
    { name: 'favicon-32.png', size: 32, rounded: true },
    { name: 'apple-touch-icon.png', size: 180, rounded: false },
  ]

  for (const { name, size, rounded } of rasterAssets) {
    await page.setViewportSize({ width: size, height: size })
    await page.setContent(
      `<style>body { margin: 0 } svg { display: block }</style>${svg(size, rounded)}`,
    )
    const png = await page.screenshot({ omitBackground: true })
    await writeAsset(`public/${name}`, png)
  }

  const formatting = await resolveConfig(resolve(root, 'index.html'))
  await writeAsset(
    'public/favicon.svg',
    await format(svg(64, true), { ...formatting, parser: 'html' }),
  )

  await writeAsset(
    'android/app/src/main/res/drawable/ic_launcher_foreground.xml',
    androidForeground(false),
  )
  await writeAsset(
    'android/app/src/main/res/drawable/ic_launcher_monochrome.xml',
    androidForeground(true),
  )

  await writeAsset(
    'android/app/src/main/res/values/ic_launcher_background.xml',
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.mjs. -->
<resources>
    <color name="ic_launcher_background">${background}</color>
</resources>
`,
  )
} finally {
  await browser.close()
}
